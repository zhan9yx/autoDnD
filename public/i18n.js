export function normalizeLanguage(value) {
  const language = String(value || "").toLowerCase();
  if (language === "zh-cn" || language === "zh-hans" || language === "zh_hans" || language === "cn") {
    return "zh";
  }
  return SUPPORTED_LANGUAGES.includes(language) ? language : DEFAULT_LANGUAGE;
}

export function t(language, key, params = {}) {
  const locale = normalizeLanguage(language);
  const template = dictionaries[locale]?.[key] ?? dictionaries[DEFAULT_LANGUAGE][key] ?? key;
  return String(template).replace(/\{(\w+)\}/g, (_, name) => params[name] ?? "");
}

export function applyTranslations(language, root = document) {
  const locale = normalizeLanguage(language);
  document.documentElement.lang = locale === "zh" ? "zh-CN" : "en";
  document.title = t(locale, "app.title");

  for (const node of root.querySelectorAll("[data-i18n]")) {
    node.textContent = t(locale, node.dataset.i18n);
  }
  for (const node of root.querySelectorAll("[data-i18n-placeholder]")) {
    node.setAttribute("placeholder", t(locale, node.dataset.i18nPlaceholder));
  }
  for (const node of root.querySelectorAll("[data-i18n-title]")) {
    node.setAttribute("title", t(locale, node.dataset.i18nTitle));
  }
  for (const node of root.querySelectorAll("[data-i18n-aria-label]")) {
    node.setAttribute("aria-label", t(locale, node.dataset.i18nAriaLabel));
  }
}
